use std::sync::{Arc, RwLock};
use std::thread;
use std::time::{Duration, Instant};

use log::{error, info};
use x11rb::{connection::Connection, protocol::Event as X11Event};

use crate::{
    models::{
        app::App,
        ui::{Display, Screen, Transition},
    },
    ui::events::{AppEvent, TouchEvent, TouchKind},
    ui::screens::HomeScreen,
    utils::config::AppConfig,
};

impl App {
    /// Creates the App by wiring together the single Display (X11 connection +
    /// renderer) and pushing the HomeScreen as the first entry on the stack.
    pub fn new() -> Result<Self, Box<dyn std::error::Error>> {
        // Load the app configuration first — it seeds the screens created
        // below (e.g. the puzzle screen's initial params). Read once from
        // the user-editable config file; see AppConfig::load.
        let config = AppConfig::load();
        info!("App config loaded: {:?}", config.puzzle);
        let config = Arc::new(RwLock::new(config));

        let mut display = Display::new()?;
        // Optional: start directly in chrome mode (Kindle status bar overlaid)
        // instead of fullscreen. Default false keeps the fullscreen behavior.
        if config.read().map(|c| c.chrome_on_start).unwrap_or(false) {
            info!("chrome_on_start — enabling status-bar chrome");
            display.set_chrome_mode(true)?;
        }
        let home: Box<dyn Screen> = Box::new(HomeScreen::new(config.clone()));
        info!("Creatinjg App Instance");

        Ok(Self {
            display,
            screen_stack: vec![home],
            config,
            locked: false,
        })
    }

    pub fn run(mut self) {
        info!("Triple-tap anywhere to emergency exit");

        // Spawn X11 listener BEFORE the first draw so MapNotify/Expose events
        // generated by Renderer::new() are picked up reliably. Mirrors the
        // historical (Kindle-working) ordering at d9fd7cf.
        self.spawn_x11_listener();

        // Device wake watcher (powerd via lipc) — None off-device, where the
        // lipc tools do not exist; the app then simply never sees DeviceWake.
        let _powerd_watcher =
            crate::system::powerd::spawn_powerd_watcher(self.display.event_tx.clone());

        // Initial render of whatever is on top of the stack
        if let Some(screen) = self.screen_stack.last_mut()
            && let Err(e) = screen.render(&mut self.display)
        {
            error!("Initial render failed: {}", e);
            return;
        }
        info!("Initial render is done");

        // Bootstrap-only periodic redraw. The Kindle's e-ink Xorg occasionally
        // drops the very first paint; we retry every 100 ms until *any*
        // X11-originated event proves the server is responsive, with a 1.5 s
        // safety cap so we don't spin forever. Once disabled, redraws happen
        // only on `Transition::Redraw` — otherwise the unconditional 10 Hz
        // redraw stacks `clear() + many put_image()` calls per frame, which
        // x11rb auto-flushes in pieces and shows up as flicker.
        let tick = Duration::from_millis(16);
        let redraw_period = Duration::from_millis(100);
        let bootstrap_deadline = Instant::now() + Duration::from_millis(1500);
        let mut x11_alive = false;
        let mut last_redraw = Instant::now();

        loop {
            // Wait for an event, but time out so we can drive periodic redraws.
            let event = match self.display.event_rx.recv_timeout(tick) {
                Ok(e) => e,
                Err(std::sync::mpsc::RecvTimeoutError::Timeout) => {
                    // Bootstrap: retry initial paint until X11 proves alive.
                    if !x11_alive
                        && !self.locked
                        && Instant::now() < bootstrap_deadline
                        && last_redraw.elapsed() >= redraw_period
                    {
                        if let Some(screen) = self.screen_stack.last_mut()
                            && let Err(e) = screen.render(&mut self.display)
                        {
                            error!("Periodic render error: {}", e);
                        }
                        last_redraw = Instant::now();
                        continue;
                    }
                    // e07s10: after bootstrap, send a Tick so screens with
                    // polling logic can check staleness without causing
                    // constant full redraws (which flicker on e-ink).
                    if x11_alive && !self.locked {
                        AppEvent::Tick(tick)
                    } else {
                        continue;
                    }
                }
                Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => {
                    info!("Event channel closed, shutting down.");
                    break;
                }
            };

            // Any X11-originated event means the server is alive — turn off
            // the bootstrap retry loop.
            if matches!(
                event,
                AppEvent::Expose | AppEvent::Touch(_) | AppEvent::WindowUnmapped
            ) {
                x11_alive = true;
            }

            // Check global triple-tap before handing to the active screen
            if let AppEvent::Touch(ref touch) = event
                && self.check_triple_tap(touch)
            {
                info!("Triple-tap detected — emergency exit");
                break;
            }

            // Display lock: powerd goingToScreenSaver. Pillow is disabled, so
            // no Amazon screensaver appears — draw our own (logo) instead, and
            // suppress app redraws until wake.
            if matches!(event, AppEvent::DeviceLock) {
                info!("Device lock — drawing custom screensaver");
                self.locked = true;
                if let Err(e) =
                    crate::ui::screensaver::render_screensaver(&mut self.display.renderer)
                {
                    error!("Screensaver render error: {}", e);
                }
                continue;
            }

            // Device wake/unlock: full redraw of the top screen so the e-ink
            // panel comes back clean after the lock (powerd outOfScreenSaver).
            // The event also flows to the top screen, which re-kicks the game
            // stream so the board refetches its latest state.
            if matches!(event, AppEvent::DeviceWake) {
                info!("Device wake — full redraw");
                self.locked = false;
                if let Some(screen) = self.screen_stack.last_mut() {
                    // The screensaver drew over the whole window while locked,
                    // so partial-render widgets have stale caches — invalidate
                    // them (same as after a Pop) before rendering, otherwise the
                    // wake redraw skips them and the screensaver stays visible.
                    screen.on_reveal();
                    if let Err(e) = screen.render(&mut self.display) {
                        error!("Wake redraw error: {}", e);
                    }
                }
            }

            // Delegate to the screen on top of the stack
            let transition = match self.screen_stack.last_mut() {
                Some(screen) => match screen.handle_event(event, &mut self.display) {
                    Ok(t) => t,
                    Err(e) => {
                        error!("Screen event error: {}", e);
                        Transition::Stay
                    }
                },
                None => {
                    // Empty stack — nothing left to show
                    break;
                }
            };

            match transition {
                Transition::Stay => {}

                // While locked the screensaver owns the panel — skip app redraws.
                Transition::Redraw => {
                    if !self.locked
                        && let Some(screen) = self.screen_stack.last_mut()
                        && let Err(e) = screen.render(&mut self.display)
                    {
                        error!("Render error: {}", e);
                    }
                }

                Transition::Push(new_screen) => {
                    self.screen_stack.push(new_screen);
                    if !self.locked
                        && let Some(screen) = self.screen_stack.last_mut()
                        && let Err(e) = screen.render(&mut self.display)
                    {
                        error!("Render error after push: {}", e);
                    }
                }

                Transition::Pop => {
                    self.screen_stack.pop();
                    if self.screen_stack.is_empty() {
                        info!("Screen stack empty — exiting");
                        break;
                    }
                    if let Some(screen) = self.screen_stack.last_mut() {
                        // The revealed screen was drawn over while covered —
                        // let it invalidate cached render state / refresh.
                        screen.on_reveal();
                        if !self.locked
                            && let Err(e) = screen.render(&mut self.display)
                        {
                            error!("Render error after pop: {}", e);
                        }
                    }
                }

                Transition::Quit => {
                    info!("Quit requested");
                    break;
                }
            }
        }

        info!("App shutting down");
    }

    /// Returns true if the given touch completes a triple-tap gesture.
    /// Resets the counter whenever taps drift more than 50 px apart or the
    /// 500 ms window expires.
    fn check_triple_tap(&mut self, touch: &TouchEvent) -> bool {
        if touch.kind != TouchKind::Down {
            return false;
        }

        let now = std::time::Instant::now();
        let pos = (touch.x, touch.y);

        match self.display.last_tap_pos {
            Some(last) if (pos.0 - last.0).abs() <= 50 && (pos.1 - last.1).abs() <= 50 => {
                self.display.tap_times.push(now);
                self.display
                    .tap_times
                    .retain(|t| now.duration_since(*t) < std::time::Duration::from_millis(500));

                if self.display.tap_times.len() >= 3 {
                    return true;
                }
            }
            _ => {
                // Too far away or first tap — reset
                self.display.tap_times.clear();
                self.display.tap_times.push(now);
                self.display.last_tap_pos = Some(pos);
            }
        }

        false
    }

    fn spawn_x11_listener(&self) {
        let tx = self.display.event_tx.clone();
        let conn = self.display.conn.clone();

        thread::spawn(move || {
            loop {
                match conn.wait_for_event() {
                    Ok(event) => {
                        let app_event = match event {
                            X11Event::Expose(_) => Some(AppEvent::Expose),

                            X11Event::ButtonPress(e) => {
                                info!("TouchDownEvent");
                                Some(AppEvent::Touch(TouchEvent {
                                    x: e.event_x,
                                    y: e.event_y,
                                    kind: TouchKind::Down,
                                }))
                            }

                            X11Event::ButtonRelease(e) => {
                                info!("TouchUpEvent");
                                Some(AppEvent::Touch(TouchEvent {
                                    x: e.event_x,
                                    y: e.event_y,
                                    kind: TouchKind::Up,
                                }))
                            }

                            // X11Event::KeyPress(_) => {
                            //     info!("Hardware button pressed");
                            //     Some(AppEvent::Quit)
                            // }
                            X11Event::UnmapNotify(_) => Some(AppEvent::WindowUnmapped),

                            _ => None,
                        };

                        if let Some(ev) = app_event
                            && tx.send(ev).is_err()
                        {
                            break; // Main thread dropped the receiver
                        }
                    }
                    Err(e) => {
                        error!("X11 error: {:?}", e);
                        break;
                    }
                }
            }
        });
    }
}
